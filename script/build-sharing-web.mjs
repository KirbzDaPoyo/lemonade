import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
export function webConfiguration(value = '', nativeScheme = '') {
  if (nativeScheme && (!value || !['project-lemonade', 'project-lemonade-dev'].includes(nativeScheme))) throw Error('Native sharing requires an approved endpoint and app scheme');
  let endpoint = '';
  if (value) {
    const url = new URL(value);
    if (url.protocol !== 'https:' || !/^[a-z0-9-]+\.supabase\.co$/.test(url.hostname) || url.port || url.username || url.password ||
      url.pathname !== '/functions/v1/shared-plan' || url.search || url.hash || url.href !== value) throw Error('Use the approved Supabase HTTPS shared-plan endpoint');
    endpoint = url.href;
  }
  const csp = `default-src 'none'; script-src 'self'; style-src 'self'; font-src 'self'; img-src 'self'; connect-src ${endpoint ? new URL(endpoint).origin : "'none'"}; object-src 'none'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'; worker-src 'none'`;
  const headers = [
    { key:'Content-Security-Policy', value:csp }, { key:'Referrer-Policy', value:'no-referrer' },
    { key:'X-Content-Type-Options', value:'nosniff' }, { key:'Permissions-Policy', value:'camera=(), microphone=(), geolocation=()' },
    { key:'Cache-Control', value:'no-store, max-age=0' }, { key:'CDN-Cache-Control', value:'no-store' },
    { key:'Vercel-CDN-Cache-Control', value:'no-store' }, { key:'X-Robots-Tag', value:'noindex, nofollow, noarchive' }
  ];
  return { endpoint, nativeScheme, config: { $schema:'https://openapi.vercel.sh/vercel.json', framework:null, buildCommand:'', installCommand:'', outputDirectory:'.', cleanUrls:true, trailingSlash:false,
    headers:[{source:'/(.*)',headers},{source:'/.well-known/apple-app-site-association',headers:[{key:'Content-Type',value:'application/json'}]}] } };
}
export function buildSharingWeb(output = resolve('web'), endpoint = '', nativeScheme = '') {
  const configuration = webConfiguration(endpoint, nativeScheme); mkdirSync(output,{recursive:true});
  const source = readFileSync(resolve('src/services/sharing-content.ts'),'utf8');
  const compiled = ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
  writeFileSync(resolve(output,'sharing-content.mjs'),'// Generated from src/services/sharing-content.ts. Run node script/build-sharing-web.mjs.\n'+compiled);
  writeFileSync(resolve(output,'sharing-config.mjs'),'// Public configuration only. Generated by node script/build-sharing-web.mjs.\nexport const endpoint = '+JSON.stringify(configuration.endpoint)+';\nexport const nativeScheme = '+JSON.stringify(configuration.nativeScheme)+';\n');
  writeFileSync(resolve(output,'vercel.json'),JSON.stringify(configuration.config,null,2)+'\n');
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  buildSharingWeb(resolve('web'),process.env.LEMONADE_SHARING_API_URL || '', process.env.LEMONADE_NATIVE_SHARING_SCHEME || '');
  console.log('Static sharing assets generated. Missing endpoint leaves retrieval disabled.');
}
